/**
 * Scaffolding for `code-citation-lint init`: generates CITATION.cff and
 * codemeta.json documents, either from a package.json or as minimal
 * placeholder templates (in the spirit of cffinit and the codemeta generator).
 */

import {stringify} from 'yaml'

export interface ScaffoldResult {
  cff: string
  codemeta: object
}

interface AuthorInfo {
  name?: string
  email?: string
  url?: string
}

/** The subset of package.json fields used for scaffolding. */
export interface MinimalPackageJson {
  name?: string
  description?: string
  version?: string
  license?: string
  keywords?: string[]
  author?: unknown
  contributors?: unknown[]
  repository?: unknown
  homepage?: string
  [key: string]: unknown
}

const CFF_HEADER = ['# This file was generated by code-citation-lint init.', '# Adjust the metadata as needed.']

/** Parses "Name <email> (url)" / "Name" author strings and objects. */
export function parseAuthor(author: unknown): AuthorInfo | undefined {
  if (author === undefined || author === null) return undefined
  if (typeof author === 'string') {
    const match = /^(.*?)(?:\s+<([^>]+)>)?(?:\s+\(([^)]+)\))?$/.exec(author.trim())
    if (match === null) return undefined
    const name = match[1] ?? ''
    const email = match[2]
    const url = match[3]
    return {
      ...(name !== '' ? {name: name.trim()} : {}),
      ...(email !== undefined ? {email} : {}),
      ...(url !== undefined ? {url} : {})
    }
  }
  if (typeof author === 'object') {
    const entry = author as Record<string, unknown>
    if (entry.name === undefined) return undefined
    return {
      name: String(entry.name),
      ...(defined(entry.email) ? {email: String(entry.email)} : {}),
      ...(defined(entry.url) ? {url: String(entry.url)} : {})
    }
  }
  return undefined
}

function defined(value: unknown): boolean {
  return value !== undefined && value !== null && value !== ''
}

/** Splits a display name into given and family names (last token = family name). */
function splitName(name: string): {given?: string; family?: string} {
  const parts = name.trim().split(/\s+/)
  if (parts.length <= 1) return {family: parts[0] ?? name}
  const family = parts.at(-1)
  return {given: parts.slice(0, -1).join(' '), family}
}

function repositoryUrl(repository: unknown): string | undefined {
  if (typeof repository === 'string') return repository.replace(/^git\+/, '').replace(/\.git$/, '')
  if (repository !== null && typeof repository === 'object') {
    const url = (repository as Record<string, unknown>).url
    if (typeof url === 'string') return url.replace(/^git\+/, '').replace(/\.git$/, '')
  }
  return undefined
}

function packageAuthors(pkg: MinimalPackageJson): AuthorInfo[] {
  const authors: AuthorInfo[] = []
  const mainAuthor = parseAuthor(pkg.author)
  if (mainAuthor !== undefined) authors.push(mainAuthor)
  for (const contributor of pkg.contributors ?? []) {
    const contributorInfo = parseAuthor(contributor)
    if (contributorInfo !== undefined) authors.push(contributorInfo)
  }
  return authors
}

/** Builds the CFF author list (person entries; url information is dropped as CFF persons have no url field). */
function cffAuthors(authors: AuthorInfo[]): Record<string, unknown>[] {
  return authors.map(author => {
    const name = author.name ?? author.email ?? ''
    const {given, family} = splitName(name)
    return {
      ...(given !== undefined && given !== '' ? {'given-names': given} : {}),
      ...(family !== undefined && family !== '' ? {'family-names': family} : {}),
      ...(defined(author.email) ? {email: author.email} : {})
    }
  })
}

/** Builds the CodeMeta author list (Person objects). */
function codemetaAuthorsFrom(authors: AuthorInfo[]): object[] {
  return authors.map(author => {
    const name = author.name ?? author.email ?? ''
    const {given, family} = splitName(name)
    return {
      '@type': 'Person',
      ...(given !== undefined && given !== '' ? {givenName: given} : {}),
      ...(family !== undefined && family !== '' ? {familyName: family} : {}),
      ...(defined(author.email) ? {email: author.email} : {}),
      ...(defined(author.url) ? {url: author.url} : {})
    }
  })
}

const PLACEHOLDER_TITLE = 'TODO: project title'
const PLACEHOLDER_DESCRIPTION = 'TODO: a short description of the project'

/**
 * Generates CITATION.cff (as YAML string) and a codemeta document.
 * Missing fields become TODO placeholders when the input is empty.
 */
export function scaffoldFromPackageJson(pkg: MinimalPackageJson): ScaffoldResult {
  const authors = packageAuthors(pkg)
  const title = defined(pkg.name) ? String(pkg.name) : PLACEHOLDER_TITLE
  const description = defined(pkg.description) ? String(pkg.description) : PLACEHOLDER_DESCRIPTION
  const version = defined(pkg.version) ? String(pkg.version) : undefined
  const license = defined(pkg.license) && pkg.license !== 'UNLICENSED' ? String(pkg.license) : undefined
  const repository = repositoryUrl(pkg.repository)
  const homepage = defined(pkg.homepage) ? String(pkg.homepage) : undefined
  const keywords = Array.isArray(pkg.keywords) && pkg.keywords.length > 0 ? pkg.keywords.map(String) : undefined

  const authorEntries = cffAuthors(authors.length > 0 ? authors : [{name: 'TODO: author name'}])
  const codemetaAuthors = codemetaAuthorsFrom(authors.length > 0 ? authors : [{name: 'TODO: author name'}])
  const cffDocument: Record<string, unknown> = {
    'cff-version': '1.2.0',
    message: 'If you use this software, please cite it using these metadata.',
    title,
    ...(description !== '' ? {abstract: description} : {}),
    authors: authorEntries,
    ...(version !== undefined ? {version} : {}),
    ...(license !== undefined ? {license} : {}),
    ...(repository !== undefined ? {'repository-code': repository} : {}),
    ...(homepage !== undefined ? {url: homepage} : {}),
    ...(keywords !== undefined ? {keywords} : {})
  }
  const codemeta: Record<string, unknown> = {
    '@context': 'https://w3id.org/codemeta/4.0',
    '@type': 'SoftwareSourceCode',
    name: title,
    description,
    author: codemetaAuthors,
    ...(license !== undefined ? {license} : {}),
    ...(repository !== undefined ? {codeRepository: repository} : {}),
    ...(version !== undefined ? {softwareVersion: version} : {}),
    ...(repository !== undefined && homepage !== undefined ? {url: homepage} : {}),
    ...(keywords !== undefined ? {keywords} : {})
  }

  const cff = `${CFF_HEADER.join('\n')}\n\n${stringify(cffDocument, {lineWidth: 0})}`
  return {cff, codemeta}
}

/** Minimal placeholder scaffold for projects without a package.json. */
export function minimalScaffold(): ScaffoldResult {
  return scaffoldFromPackageJson({})
}
